/**
 * Run-level media identity ledger for Flow batch generation.
 *
 * Root cause it fixes (run flowTutor-1793720826350-iv53k8): `waitForNewImageTile`
 * judged "freshness" only against the cards mounted at the START of the current
 * generation call. Clip 6's start-image call excluded only the reference card
 * (clip 5 END), so the still-mounted clip 5 START card was treated as the "new" card;
 * clip 6's end-image call excluded only clip 5 START, so clip 5 END came back. Both
 * clip-006 JPEGs were byte-identical to clip-005's.
 *
 * The canvas is virtualized and recycles cards, so the ONLY reliable notion of
 * "already consumed" is a run-scoped ledger of every media identity the run has ever
 * recorded (script entries + freshly generated media). Every image-generation call
 * excludes the whole ledger, and downloaded keyframes are additionally verified by
 * content hash so a repeat can never slip through silently.
 */
import { canonicalMediaTokens, hashMediaFile } from './duplicate-guard.js';

export interface ScriptClipMediaRef {
  clipIndex?: number;
  imageUrl?: string | null;
  endImageUrl?: string | null;
  imageTileKey?: string | null;
  endImageTileKey?: string | null;
  videoUrl?: string | null;
  localImagePath?: string | null;
  localEndImagePath?: string | null;
  localVideoPath?: string | null;
  startFramePath?: string | null;
}

export class MediaIdentityLedger {
  /** canonical identity token -> human-readable owner label */
  private readonly tokens = new Map<string, string>();
  /** sha1 of a generated keyframe -> owning clip label */
  private readonly keyframeHashes = new Map<string, string>();

  private constructor() {}

  /**
   * Seeds the ledger from EVERY clip of the script (completed and pending), so a
   * resumed run can never re-consume media generated by an earlier session.
   */
  static async seedFromScriptClips(clips: ScriptClipMediaRef[]): Promise<MediaIdentityLedger> {
    const ledger = new MediaIdentityLedger();
    for (const clip of clips) {
      const label = `clip-${String(clip.clipIndex ?? '?').padStart(3, '0')}`;
      ledger.add(`${label} start`, [clip.imageUrl, clip.imageTileKey, clip.localImagePath]);
      ledger.add(`${label} end`, [clip.endImageUrl, clip.endImageTileKey, clip.localEndImagePath]);
      ledger.add(`${label} video`, [clip.videoUrl, clip.localVideoPath, clip.startFramePath]);
      // Content-level seed: an existing keyframe on disk is consumed media too.
      await ledger.registerKeyframe(`${label} start`, clip.localImagePath ?? null);
      await ledger.registerKeyframe(`${label} end`, clip.localEndImagePath ?? null);
    }
    return ledger;
  }

  /** Registers one or more media references (URL / tile key / file path) under an owner. */
  add(owner: string, refs: Array<string | null | undefined>): void {
    for (const ref of refs) {
      for (const token of canonicalMediaTokens(ref)) {
        if (!this.tokens.has(token)) this.tokens.set(token, owner);
      }
    }
  }

  /** True when the reference was already consumed by this run. */
  has(ref: string | null | undefined): boolean {
    return this.ownerOf(ref) !== null;
  }

  /** Owning label of an already-consumed reference, or null when it is genuinely new. */
  ownerOf(ref: string | null | undefined): string | null {
    for (const token of canonicalMediaTokens(ref)) {
      const owner = this.tokens.get(token);
      if (owner) return owner;
    }
    return null;
  }

  /** Snapshot for `generateClipImage({ excludeKeys })` — every consumed identity. */
  snapshot(): string[] {
    return [...this.tokens.keys()];
  }

  /**
   * Registers a downloaded keyframe by content hash. Returns the owning label when the
   * exact same bytes were already generated (i.e. the canvas handed back old media),
   * otherwise null.
   */
  async registerKeyframe(owner: string, filePath: string | null | undefined): Promise<string | null> {
    if (!filePath) return null;
    const hash = await hashMediaFile(filePath);
    if (!hash) return null;
    const prior = this.keyframeHashes.get(hash) ?? null;
    if (!prior) this.keyframeHashes.set(hash, owner);
    return prior;
  }
}

/**
 * Cross-clip duplicate keyframe identity, e.g. clip-006 reusing clip-005's start image.
 * A script produced before the ledger fix can still CARRY such corruption on disk, so
 * the batch repairs it up-front instead of reusing the wrong frames forever.
 */
export interface DuplicateKeyframeFinding {
  clipIndex: number;
  field: 'start' | 'end';
  ownerClipIndex: number;
  identity: string;
}

/**
 * Finds keyframe identities recorded by MORE than one clip (or by both slots of one
 * clip). The first clip in story order keeps the media; the later clip is the duplicate
 * that must be regenerated.
 */
export function findCrossClipDuplicateKeyframes(clips: ScriptClipMediaRef[]): DuplicateKeyframeFinding[] {
  const owners = new Map<string, { clipIndex: number; field: 'start' | 'end' }>();
  const findings: DuplicateKeyframeFinding[] = [];
  const reported = new Set<string>();

  const ordered = [...clips].sort((a, b) => (a.clipIndex ?? 0) - (b.clipIndex ?? 0));
  for (const clip of ordered) {
    const clipIndex = clip.clipIndex ?? 0;
    const slots: Array<{ field: 'start' | 'end'; refs: Array<string | null | undefined> }> = [
      { field: 'start', refs: [clip.imageUrl, clip.imageTileKey] },
      { field: 'end', refs: [clip.endImageUrl, clip.endImageTileKey] },
    ];
    for (const slot of slots) {
      for (const ref of slot.refs) {
        for (const token of canonicalMediaTokens(ref)) {
          const prior = owners.get(token);
          if (prior && (prior.clipIndex !== clipIndex || prior.field !== slot.field)) {
            // One finding per (clip, slot, owner): each ref yields several identity tokens.
            const findingKey = `${clipIndex}:${slot.field}:${prior.clipIndex}:${prior.field}`;
            if (!reported.has(findingKey)) {
              reported.add(findingKey);
              findings.push({
                clipIndex,
                field: slot.field,
                ownerClipIndex: prior.clipIndex,
                identity: token,
              });
            }
          } else if (!prior) {
            owners.set(token, { clipIndex, field: slot.field });
          }
        }
      }
    }
  }
  return findings;
}
