const execFileAsync = promisify(execFile);

const TUTORIAL_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TIMELINE_PATH = path.join(TUTORIAL_DIR, 'tutorial.json');
const NARRATION_WAV_PATH = path.join(TUTORIAL_DIR, 'assets', 'narration.wav');
const VIDEO_FILENAME = 'tutorial-video.mp4';
const SILENT_FILENAME = 'tutorial-silent.mp4';
