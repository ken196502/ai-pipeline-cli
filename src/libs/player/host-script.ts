function parseArgs(argv) {
  const opts = {
    port: DEFAULT_PORT,
    bind: DEFAULT_BIND,
    gpu: 'metal',
    engine: 'chromium',
    allowRoot: DEFAULT_ALLOW_ROOT,
    maxQueue: 1,
    idleTimeoutSec: 0,
    jobTimeoutSec: 3600,
  };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    const next = () => {
      const value = argv[i + 1];
      if (value === undefined) throw new Error('missing value for ' + a);
      i += 1;
      return value;
    };
    if (a === '--port') opts.port = Number(next());
    else if (a === '--bind') opts.bind = next();
    else if (a === '--gpu') opts.gpu = next();
    else if (a === '--token') opts.token = next();
    else if (a === '--engine') opts.engine = next();
    else if (a === '--browser') opts.browserPath = next();
    else if (a === '--allow-root') opts.allowRoot = next();
    else if (a === '--max-queue') opts.maxQueue = Number(next());
    else if (a === '--idle-timeout') opts.idleTimeoutSec = Number(next());
    else if (a === '--job-timeout') opts.jobTimeoutSec = Number(next());
    else if (a === '--help' || a === '-h') { printUsage(); process.exit(0); }
    else throw new Error('unknown argument: ' + a);
  }
  return opts;
}

