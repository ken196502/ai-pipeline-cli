/**
 * Host-side render helper generation (宿主机渲染脚本).
 *
 * The VM's CPU is far too slow for the frame-by-frame explainer render, so every
 * generated explainer bundle ships with a double-clickable bash script
 * (render-on-host.command) plus a standalone Node renderer
 * (host-render/render.mjs). The user double-clicks the .command file in the
 * macOS Finder (shared folder) and the host machine performs the heavy render:
 * headless frame capture (LOCAL Firefox via Playwright WebDriver BiDi when
 * Firefox is installed, otherwise the explicit Chromium/Chrome path) → ffmpeg
 * encode → narration mux → grid.
 *
 * The generated renderer intentionally avoids importing anything from this
 * project: the node_modules tree was installed on the Linux VM, so native
 * modules (sharp) cannot load on the host. Only playwright-core (pure JS) and
 * node built-ins are required; playwright-core resolves up the shared directory
 * tree into the project node_modules.
 */
import fs from 'node:fs/promises';
import path from 'node:path';

export const HOST_RENDER_SCRIPT_FILENAME = 'render-on-host.command';
export const HOST_RENDER_DIRNAME = 'host-render';
export const HOST_RENDERER_FILENAME = 'render.mjs';

/** Standalone ESM renderer — faithful port of src/libs/player/render.ts. */
const HOST_RENDERER_SOURCE = `#!/usr/bin/env node
/**
 * Standalone host-side renderer for the OpusVideo explainer bundle.
 *
 * Generated by src/libs/player/host-script.ts — do not edit by hand;
 * it is rewritten on every explainer generation. This file must stay
 * dependency-minimal: node built-ins + playwright-core only.
 *
 * Usage: node render.mjs [--engine firefox|chromium] [--browser <path>] [--crf N] [--preset name] [--fps N]
 */
import http from 'node:http';
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn, execFile, execFileSync } from 'node:child_process';
import { promisify } from 'node:util';
import { chromium, firefox } from 'playwright-core';

const execFileAsync = promisify(execFile);

const EXPLAINER_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TIMELINE_PATH = fs.existsSync(path.join(EXPLAINER_DIR, 'explainer.json'))
  ? path.join(EXPLAINER_DIR, 'explainer.json')
  : path.join(EXPLAINER_DIR, 'tutorial.json');
const NARRATION_WAV_PATH = path.join(EXPLAINER_DIR, 'assets', 'narration.wav');
const VIDEO_FILENAME = 'explainer-video.mp4';
const SILENT_FILENAME = 'explainer-silent.mp4';
const GRID_FILENAME = 'explainer-grid.jpg';
const FIREFOX_PROFILE_DIR = path.join(EXPLAINER_DIR, 'host-render', 'firefox-profile');

const CONTENT_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.mp4': 'video/mp4',
  '.webm': 'video/webm',
  '.mov': 'video/quicktime',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.svg': 'image/svg+xml',
  '.mp3': 'audio/mpeg',
  '.m4a': 'audio/mp4',
  '.wav': 'audio/wav',
};

function firefoxInstalled() {
  const candidates = [
    '/Applications/Firefox.app/Contents/MacOS/firefox',
    path.join(process.env.HOME || '', 'Applications/Firefox.app/Contents/MacOS/firefox'),
  ];
  if (candidates.some((c) => fs.existsSync(c))) return true;
  try {
    execFileSync('firefox', ['--version'], { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

function resolveChromiumExecutable(explicitPath) {
  if (explicitPath && fs.existsSync(explicitPath)) return explicitPath;
  const envPath = process.env.CHROME_PATH || process.env.CHROMIUM_PATH;
  if (envPath && fs.existsSync(envPath)) return envPath;
  const candidates = [
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    path.join(process.env.HOME || '', 'Applications/Google Chrome.app/Contents/MacOS/Google Chrome'),
    '/Applications/Chromium.app/Contents/MacOS/Chromium',
    path.join(process.env.HOME || '', 'Applications/Chromium.app/Contents/MacOS/Chromium'),
    '/usr/bin/google-chrome-stable',
    '/usr/bin/chromium-browser',
    '/usr/bin/chromium',
  ];
  for (const c of candidates) {
    if (fs.existsSync(c)) return c;
  }
  return null;
}

function parseCliArgs() {
  const args = process.argv.slice(2);
  const opts = { crf: 20, preset: 'medium' };
  for (let i = 0; i < args.length; i += 1) {
    const a = args[i];
    if (a === '--engine' && args[i + 1]) { opts.engine = args[++i]; }
    else if (a === '--browser' && args[i + 1]) { opts.browserPath = args[++i]; }
    else if (a === '--crf' && args[i + 1]) { opts.crf = Number(args[++i]); }
    else if (a === '--preset' && args[i + 1]) { opts.preset = args[++i]; }
    else if (a === '--fps' && args[i + 1]) { opts.fps = Number(args[++i]); }
  }
  return opts;
}

async function serveDirectory(dir) {
  const root = path.resolve(dir);
  const defaultHtml = fs.existsSync(path.join(root, 'explainer-player.html'))
    ? 'explainer-player.html'
    : 'tutorial-player.html';

  const server = http.createServer((req, res) => {
    const requestPath = decodeURIComponent((req.url || '/').split('?')[0]);
    const rel = requestPath === '/' ? defaultHtml : requestPath.slice(1);
    const filePath = path.join(root, rel);

    if (!filePath.startsWith(root) || !fs.existsSync(filePath) || !fs.statSync(filePath).isFile()) {
      res.statusCode = 404;
      res.end('not found');
      return;
    }

    res.setHeader('Content-Type', CONTENT_TYPES[path.extname(filePath).toLowerCase()] || 'application/octet-stream');
    res.setHeader('Accept-Ranges', 'bytes');
    const size = fs.statSync(filePath).size;
    let start = 0, end = size - 1;
    if (req.headers.range) {
      const match = /^bytes=(\\d*)-(\\d*)$/.exec(req.headers.range);
      if (match && (match[1] || match[2])) {
        start = match[1] ? Number(match[1]) : Math.max(0, size - Number(match[2]));
        end = match[1] && match[2] ? Math.min(Number(match[2]), size - 1) : size - 1;
      }
      if (!match || (!match[1] && !match[2]) || start > end || start >= size) {
        res.writeHead(416, { 'Content-Range': 'bytes */' + size });
        res.end();
        return;
      }
      res.statusCode = 206;
      res.setHeader('Content-Range', 'bytes ' + start + '-' + end + '/' + size);
    }
    res.setHeader('Content-Length', Math.max(0, end - start + 1));
    if (req.method === 'HEAD' || size === 0) { res.end(); return; }
    fs.createReadStream(filePath, { start, end }).pipe(res);
  });

  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', () => resolve());
  });

  const address = server.address();
  return {
    origin: 'http://127.0.0.1:' + address.port,
    close: () => new Promise((resolve) => server.close(resolve)),
  };
}

async function probeDuration(filePath) {
  try {
    const { stdout } = await execFileAsync('ffprobe', [
      '-v', 'error',
      '-show_entries', 'format=duration',
      '-of', 'default=noprint_wrappers=1:nokey=1',
      filePath,
    ]);
    const num = Number(stdout.trim());
    return Number.isFinite(num) && num > 0 ? num : 0;
  } catch {
    return 0;
  }
}

async function main() {
  const opts = parseCliArgs();
  console.log('--- Host-Side Explainer Video Renderer ---');

  if (!fs.existsSync(TIMELINE_PATH)) {
    throw new Error('timeline file not found at: ' + TIMELINE_PATH);
  }
  const timeline = JSON.parse(await fsp.readFile(TIMELINE_PATH, 'utf-8'));
  const width = (timeline.resolution && timeline.resolution.width) || 1920;
  const height = (timeline.resolution && timeline.resolution.height) || 1080;
  const fps = opts.fps || timeline.fps || 30;
  const totalDurationSec = timeline.totalDurationSec;

  if (!width || !height || !fps || !totalDurationSec) {
    throw new Error('timeline is missing resolution/fps/totalDurationSec — regenerate the explainer bundle on the VM');
  }
  if (!fs.existsSync(NARRATION_WAV_PATH)) {
    throw new Error('narration track not found: ' + NARRATION_WAV_PATH);
  }

  const defaultHtml = fs.existsSync(path.join(EXPLAINER_DIR, 'explainer-player.html'))
    ? 'explainer-player.html'
    : 'tutorial-player.html';

  const totalFrames = Math.max(1, Math.round(totalDurationSec * fps));
  console.log('Timeline: ' + width + 'x' + height + ' @ ' + fps + 'fps, duration ' + totalDurationSec.toFixed(1) + 's (' + totalFrames + ' frames)');

  const engine = opts.engine || (firefoxInstalled() ? 'firefox' : 'chromium');
  console.log('Render Engine: ' + engine);

  let browser;
  let page;
  if (engine === 'firefox') {
    await fsp.mkdir(FIREFOX_PROFILE_DIR, { recursive: true });
    for (const lock of ['lock', '.parentlock', 'parent.lock']) {
      await fsp.rm(path.join(FIREFOX_PROFILE_DIR, lock), { force: true }).catch(() => undefined);
    }
    const context = await firefox.launchPersistentContext(FIREFOX_PROFILE_DIR, {
      headless: true,
      viewport: { width, height },
      deviceScaleFactor: 1,
      firefoxUserPrefs: {
        'layers.acceleration.force-enabled': true,
        'webgl.force-enabled': true,
        'gfx.webrender.all': true,
      },
    });
    browser = context;
    page = context.pages()[0] || (await context.newPage());
  } else {
    const executablePath = resolveChromiumExecutable(opts.browserPath);
    if (!executablePath) throw new Error('No Chromium/Chrome executable found on host.');
    browser = await chromium.launch({
      executablePath,
      headless: true,
      args: ['--no-sandbox', '--disable-setuid-sandbox', '--hide-scrollbars', '--force-device-scale-factor=1'],
    });
    page = await browser.newPage({ viewport: { width, height } });
  }

  await page.setViewportSize({ width, height });

  const server = await serveDirectory(EXPLAINER_DIR);
  const silentVideoPath = path.join(EXPLAINER_DIR, SILENT_FILENAME);
  const outVideoPath = path.join(EXPLAINER_DIR, VIDEO_FILENAME);

  try {
    console.log('Booting explainer player in render mode...');
    await page.goto(server.origin + '/' + defaultHtml + '?render=1', { waitUntil: 'load', timeout: 120000 });
    await page.waitForFunction(
      'window.__explainerReady === true || window.__tutorialReady === true || window.__explainerError || window.__tutorialError',
      undefined,
      { timeout: 120000 }
    );
    const bootError = await page.evaluate('window.__explainerError || window.__tutorialError || null');
    if (bootError) throw new Error('explainer player failed to boot: ' + bootError);

    await page.evaluate(() => {
      document.documentElement.classList.add('render-mode');
      document.body.classList.add('render-mode');
      document.getElementById('hud')?.remove();
      document.getElementById('controls')?.remove();
    });

    console.log('Starting ffmpeg frame capture pipe...');
    const ffmpegProc = spawn('ffmpeg', [
      '-y',
      '-f', 'image2pipe',
      '-framerate', String(fps),
      '-i', 'pipe:0',
      '-vf', 'setsar=1/1',
      '-aspect', '16:9',
      '-c:v', 'libx264',
      '-preset', opts.preset || 'medium',
      '-crf', String(opts.crf ?? 20),
      '-pix_fmt', 'yuv420p',
      '-r', String(fps),
      silentVideoPath,
    ]);

    const ffmpegExit = new Promise((resolve, reject) => {
      ffmpegProc.once('error', reject);
      ffmpegProc.once('close', (code) => resolve(code));
    });

    const stdin = ffmpegProc.stdin;
    const startMs = Date.now();

    for (let frame = 0; frame < totalFrames; frame++) {
      const t = frame / fps;
      await page.evaluate((time) => {
        const api = window.__explainer || window.__tutorial;
        return api.seek(time);
      }, t);
      const pngBuffer = await page.screenshot({ type: 'png' });
      await new Promise((resolve, reject) => {
        stdin.write(pngBuffer, (err) => (err ? reject(err) : resolve()));
      });
      if ((frame + 1) % 100 === 0 || frame === totalFrames - 1) {
        const pct = (((frame + 1) / totalFrames) * 100).toFixed(1);
        const fpsReal = ((frame + 1) / ((Date.now() - startMs) / 1000)).toFixed(1);
        console.log('Rendering: ' + (frame + 1) + '/' + totalFrames + ' frames (' + pct + '%, ' + fpsReal + ' fps)');
      }
    }

    stdin.end();
    const code = await ffmpegExit;
    if (code !== 0) throw new Error('ffmpeg silent encode failed with exit code ' + code);

    console.log('Muxing narration audio with silent video...');
    await execFileAsync('ffmpeg', [
      '-y',
      '-i', silentVideoPath,
      '-i', NARRATION_WAV_PATH,
      '-map', '0:v:0',
      '-map', '1:a:0',
      '-c:v', 'copy',
      '-c:a', 'aac',
      '-b:a', '192k',
      '-movflags', '+faststart',
      outVideoPath,
    ]);

    console.log('Video render completed: ' + outVideoPath);
  } finally {
    if (browser) await browser.close().catch(() => undefined);
    await server.close();
  }
}

main().catch((err) => {
  console.error('Render failed:', err);
  process.exit(1);
});
`;

/** Standalone macOS bash runner (.command). */
const HOST_SCRIPT_SOURCE = `#!/usr/bin/env bash
set -e
trap 'exit 1' INT TERM

SCRIPT_DIR="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
EXPLAINER_DIR="\$SCRIPT_DIR"
cd "\$EXPLAINER_DIR"

log() { printf "\\033[1;36m[aigc-render]\\033[0m %s\\n" "\$*"; }
info() { printf "\\033[1;30m[aigc-render]\\033[0m %s\\n" "\$*"; }
fail() { printf "\\033[1;31m[aigc-render] ERROR:\\033[0m %s\\n" "\$*" >&2; exit 1; }

log "Starting Host-Side Explainer Video Render..."

if ! command -v node >/dev/null 2>&1; then
  fail "Node.js not found in PATH — install Node.js (https://nodejs.org) on this host machine"
fi

if ! command -v ffmpeg >/dev/null 2>&1; then
  fail "ffmpeg not found in PATH — install ffmpeg (brew install ffmpeg) on this host machine"
fi

[ -f "\$EXPLAINER_DIR/explainer.json" ] || [ -f "\$EXPLAINER_DIR/tutorial.json" ] || fail "explainer.json not found here"
[ -f "\$EXPLAINER_DIR/assets/narration.wav" ] || fail "assets/narration.wav not found"
[ -f "\$EXPLAINER_DIR/host-render/render.mjs" ] || fail "host-render/render.mjs missing"

node "\$EXPLAINER_DIR/host-render/render.mjs" "\$@"

if command -v open >/dev/null 2>&1; then
  open -R "\$EXPLAINER_DIR/explainer-video.mp4" >/dev/null 2>&1 || true
fi

log "Done: \$EXPLAINER_DIR/explainer-video.mp4"
`;

export interface WriteHostRenderScriptResult {
  scriptPath: string;
  rendererPath: string;
}

/**
 * Writes the double-clickable host render script and its standalone renderer
 * into the explainer bundle directory. Both are executable.
 */
export async function writeHostRenderScript(params: {
  explainerDir?: string;
  tutorialDir?: string;
}): Promise<WriteHostRenderScriptResult> {
  const targetDir = path.resolve(params.explainerDir || params.tutorialDir || '');
  const hostRenderDir = path.join(targetDir, HOST_RENDER_DIRNAME);
  await fs.mkdir(hostRenderDir, { recursive: true });

  const scriptPath = path.join(targetDir, HOST_RENDER_SCRIPT_FILENAME);
  const rendererPath = path.join(hostRenderDir, HOST_RENDERER_FILENAME);
  await fs.writeFile(scriptPath, HOST_SCRIPT_SOURCE, { mode: 0o755 });
  await fs.writeFile(rendererPath, HOST_RENDERER_SOURCE, { mode: 0o755 });

  return { scriptPath, rendererPath };
}
