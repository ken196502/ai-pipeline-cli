/**
 * Host-side render helper generation (宿主机渲染脚本).
 *
 * The VM's CPU is far too slow for the frame-by-frame explainer render, so every
 * generated explainer bundle ships with:
 *   - render-on-host.command          double-click single render (manual fallback)
 *   - start-render-service.command    double-click resident HTTP render service
 *   - host-render/render-core.mjs     shared render core (static server → browser
 *                                     frames → ffmpeg → mux → grid)
 *   - host-render/render.mjs          thin CLI around render-core.mjs
 *   - host-render/server.mjs          resident HTTP service (jobs, SSE, auth)
 *
 * The user double-clicks a .command file in the macOS Finder (shared folder) and
 * the host machine performs the heavy render: headless frame capture (LOCAL
 * Firefox via Playwright WebDriver BiDi when Firefox is installed, otherwise the
 * explicit Chromium/Chrome path) → ffmpeg encode → narration mux → grid.
 *
 * The generated files intentionally avoid importing anything from this project:
 * the node_modules tree was installed on the Linux VM, so native modules (sharp)
 * cannot load on the host. Only playwright-core (pure JS) and node built-ins are
 * required; playwright-core resolves up the shared directory tree into the
 * project node_modules.
 */
