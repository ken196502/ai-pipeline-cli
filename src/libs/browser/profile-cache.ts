/**
 * Chromium profile cache management.
 *
 * A persistent profile is copied from the system Chromium so the pipelines keep
 * a logged-in session. The problem: Chromium's own caches dominate the copy —
 * a real profile here measured 1.4 GB, of which 1.34 GB was
 * `Default/Cache` (993 MB) + `Default/Service Worker` (244 MB) + `Default/Code Cache` (106 MB).
 *
 * This module provides:
 *  - `PROFILE_SKIP_DIRS`: cache/telemetry directories that are never copied,
 *  - `pruneProfile()`: delete them from an existing profile (login is kept),
 *  - `profileInUse()`: never prune a profile a live Chromium still owns.
 *
 * What is deliberately KEPT: Cookies, Network, Local Storage, IndexedDB,
 * Session Storage, Preferences, Login Data — the session lives there.
 */
import fs from 'node:fs/promises';
import path from 'node:path';

const MB = 1024 * 1024;

/** Files that are meaningless in a copied profile (locks, metrics, temp). */
export const PROFILE_IGNORE_FILES = new Set([
  'SingletonLock',
  'SingletonCookie',
  'SingletonSocket',
  'LOCK',
  'BrowserMetrics-spare.pma',
  'chrome_debug.log',
]);

/** Runtime files that must survive pruning: a live browser may still own them. */
const PROFILE_RUNTIME_FILES = new Set(['SingletonLock', 'SingletonCookie', 'SingletonSocket', 'LOCK']);

/**
 * Directories skipped on copy and deleted by `pruneProfile()`.
 * All of them are regenerated by Chromium on demand.
 */
export const PROFILE_SKIP_DIRS = new Set([
  // HTTP / media / GPU caches
  'Cache',
  'Code Cache',
  'GPUCache',
  'GPUPersistentCache',
  'DawnCache',
  'DawnGraphiteCache',
  'DawnWebGPUCache',
  'GraphiteDawnCache',
  'GrShaderCache',
  'ShaderCache',
  'Service Worker',
  'CacheStorage',
  'Media Cache',
  'Application Cache',
  'blob_storage',
  'File System',
  // crash reports and telemetry
  'BrowserMetrics',
  'Crashpad',
  'Crash Reports',
  'Sessions',
  // bundled models / blocklists / dictionaries shipped by Chromium itself
  'WasmTtsEngine',
  'OnDeviceHeadSuggestModel',
  'component_crx_cache',
  'optimization_guide_hint_cache_store',
  'Safe Browsing',
  'CertificateRevocation',
  'Subresource Filter',
  'OptimizationHints',
  'MEIPreload',
  'Dictionaries',
  'hyphen-data',
  'ZxcvbnData',
  'ActorSafetyLists',
  'Crowd Deny',
  'PKIMetadata',
  'SafetyTips',
  'segmentation_platform',
  'TrustTokenKeyCommitments',
  'FirstPartySetsPreloaded',
  'OptimizationGuideModelsManifest',
  'OriginTrials',
  'AutofillStates',
  'WidevineCdm',
]);

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < MB) return `${(bytes / 1024).toFixed(0)} KB`;
  return `${(bytes / MB).toFixed(1)} MB`;
}

/** Total size of a directory tree in bytes. Unreadable entries are ignored. */
export async function dirSizeBytes(dir: string): Promise<number> {
  let total = 0;
  const walk = async (current: string): Promise<void> => {
    const entries = await fs.readdir(current, { withFileTypes: true }).catch(() => []);
    for (const entry of entries) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) {
        await walk(full);
      } else if (entry.isFile()) {
        const stat = await fs.stat(full).catch(() => null);
        if (stat) total += stat.size;
      }
    }
  };
  await walk(dir);
  return total;
}

function pidAlive(pid: number): boolean {
  if (!Number.isFinite(pid) || pid <= 0) return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch {
    return false;
  }
}

/**
 * Is a Chromium still running on this profile?
 * Reads the `SingletonLock` symlink (`<hostname>-<pid>`), falling back to the
 * pid recorded in `.browser-session.json`.
 */
export async function profileInUse(profileDir: string): Promise<{ inUse: boolean; pid?: number }> {
  try {
    const target = await fs.readlink(path.join(profileDir, 'SingletonLock'));
    const pid = Number(target.split('-').pop());
    if (pidAlive(pid)) return { inUse: true, pid };
  } catch {
    /* not a symlink, or no lock */
  }
  try {
    const raw = await fs.readFile(path.join(profileDir, '.browser-session.json'), 'utf8');
    const session = JSON.parse(raw) as { pid?: number };
    if (typeof session.pid === 'number' && pidAlive(session.pid)) {
      return { inUse: true, pid: session.pid };
    }
  } catch {
    /* no session file */
  }
  return { inUse: false };
}

export interface PruneResult {
  profileDir: string;
  /** Removed cache directories, relative to the profile root. */
  removedDirs: string[];
  /** Removed junk files (`.pma`, `.tmp`, crash dumps, logs). */
  removedFiles: number;
  freedBytes: number;
  remainingBytes: number;
  /** True when pruning was skipped because a browser still owns the profile. */
  skipped: boolean;
  /** Pid of the browser that blocked pruning. */
  pid?: number;
  /** Files that would be removed (dry run). */
  dryRun?: boolean;
}

export interface PruneOptions {
  /** Prune even when a browser is running on the profile. Default: false. */
  force?: boolean;
  /** Only report what would be removed. */
  dryRun?: boolean;
}

/**
 * Delete cache / telemetry directories from a Chromium profile.
 *
 * Cookies, Local Storage, IndexedDB and Preferences are untouched, so existing
 * logins survive. Lock files and `.browser-session.json` are also kept: a
 * running Chromium may still own them.
 */
export async function pruneProfile(
  profileDir: string,
  options: PruneOptions = {}
): Promise<PruneResult> {
  const result: PruneResult = {
    profileDir,
    removedDirs: [],
    removedFiles: 0,
    freedBytes: 0,
    remainingBytes: 0,
    skipped: false,
  };

  const inUse = await profileInUse(profileDir);
  if (inUse.inUse && !options.force) {
    return {
      ...result,
      skipped: true,
      pid: inUse.pid,
      remainingBytes: await dirSizeBytes(profileDir),
    };
  }

  const walk = async (dir: string, rel: string): Promise<void> => {
    const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      const relPath = rel ? `${rel}/${entry.name}` : entry.name;

      if (entry.isDirectory()) {
        if (PROFILE_SKIP_DIRS.has(entry.name)) {
          result.freedBytes += await dirSizeBytes(full);
          result.removedDirs.push(relPath);
          if (!options.dryRun) await fs.rm(full, { recursive: true, force: true });
          continue;
        }
        await walk(full, relPath);
        continue;
      }

      if (PROFILE_RUNTIME_FILES.has(entry.name)) continue;
      const junk =
        PROFILE_IGNORE_FILES.has(entry.name) ||
        entry.name.endsWith('.pma') ||
        entry.name.endsWith('.tmp');
      if (!junk) continue;

      const stat = await fs.stat(full).catch(() => null);
      if (stat) result.freedBytes += stat.size;
      result.removedFiles++;
      if (!options.dryRun) await fs.unlink(full).catch(() => {});
    }
  };

  await walk(profileDir, '');
  result.remainingBytes = options.dryRun
    ? Math.max(0, (await dirSizeBytes(profileDir)) - result.freedBytes)
    : await dirSizeBytes(profileDir);
  if (options.dryRun) result.dryRun = true;
  return result;
}
